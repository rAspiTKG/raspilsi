// ============================================================================
// BAYER_EX_PKG : 構成定数・型・共通関数
//   BAYER_EX は、BAYER2RGB を簡単にした演習用のコア。
//   Bayer 画像の水平4画素 × 垂直2ラインを1転送で受け取り、画素ごとに
//   黒レベル補正とゲインをかけて、同じ形の Bayer で出す(RGB には変換しない)。
// ============================================================================
package BAYER_EX_PKG;

  // --------------------------------------------------------------------------
  // 構成定数
  // --------------------------------------------------------------------------
  localparam int PIX_W     = 14;            // 画素のビット幅
  localparam int BLK_X     = 4;             // 1転送の水平の画素数
  localparam int BLK_Y     = 2;             // 1転送の垂直のライン数
  localparam int GAIN_W    = 16;            // ゲインのビット幅(U4.12)
  localparam int GAIN_FRAC = 12;            // ゲインの小数部のビット数
  localparam int PIX_MAX   = (1<<PIX_W)-1;  // 画素の最大値(16383)
  localparam logic [GAIN_W-1:0] GAIN_ONE = GAIN_W'(1<<GAIN_FRAC);  // 1.0倍(0x1000)

  // --------------------------------------------------------------------------
  // 1転送のデータ: Bayer の水平4画素 × 垂直2ライン
  //   pix[y][x]: y = 0(上のライン)/ 1(下のライン)、x = 0〜3(左から)
  //   1転送の左上の画素は、フレームの偶数ラインの、4の倍数の列にある
  // --------------------------------------------------------------------------
  typedef struct packed {
    logic                                   sof;  // フレームの最初の転送
    logic                                   eol;  // 2ラインの最後(右端)の転送
    logic                                   eof;  // フレームの最後の転送
    logic [BLK_Y-1:0][BLK_X-1:0][PIX_W-1:0] pix;  // 画素 pix[y][x]
  } bayer4x2_t;

  localparam int DATA_W = $bits(bayer4x2_t);  // 115

  // --------------------------------------------------------------------------
  // 設定(準静的。コアの中にデータがないときだけ変える)
  // --------------------------------------------------------------------------
  typedef struct packed {
    logic                   bypass;  // 1: 補正しない(入力の画素をそのまま出す)
    logic [1:0]             phase;   // Bayer の並び 0:RGGB 1:GRBG 2:GBRG 3:BGGR
    logic [3:0][PIX_W-1:0]  blc;     // 黒レベル [0]R [1]Gr [2]Gb [3]B
    logic [3:0][GAIN_W-1:0] gain;    // ゲイン(U4.12) [0]R [1]Gr [2]Gb [3]B
  } cfg_t;

  localparam int CFG_W = $bits(cfg_t);  // 123

  // --------------------------------------------------------------------------
  // Bayer の色の位置: 0:R 1:Gr 2:Gb 3:B
  //   ypar: ラインの偶奇(転送の中の y)、xpar: 列の偶奇(転送の中の x の最下位ビット)
  // --------------------------------------------------------------------------
  function automatic logic [1:0] f_site( input logic [1:0] phase, input logic ypar, input logic xpar );
    begin
      f_site = {ypar^phase[1], xpar^phase[0]};
    end
  endfunction

endpackage
